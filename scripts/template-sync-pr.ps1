<#
.SYNOPSIS
  Opens (or refreshes) one PR in the current game repo with the files the template owns (ADR 0069).
.DESCRIPTION
  Clones the template at -Ref, asks template-sync.ps1 what differs, and does nothing when nothing does.
  Otherwise it commits the changes on `chore/template-sync` (cut from the base branch), opens an issue
  and a PR to the base branch with label `template-sync`, and never merges. If a PR from that branch is
  already open it only refreshes the branch and comments on it.
  Needs: git, gh (authenticated), pwsh 7. Run it from the game repo root.
.PARAMETER Ref            Template branch or tag to sync from. Default main (released state).
.PARAMETER Base           Game branch the PR targets. Default develop.
.PARAMETER SkipWorkflows  Leave .github/workflows/* out (the token cannot push workflow files).
.PARAMETER DryRun         Print what would change and stop.
#>
[CmdletBinding()]
param(
    [string]$TemplateRepo = 'Nashei-Studios/roblox-game-template',
    [string]$Ref = 'main',
    [string]$Base = 'develop',
    [string]$Branch = 'chore/template-sync',
    [switch]$SkipWorkflows,
    [switch]$DryRun
)
$ErrorActionPreference = 'Stop'

function Invoke-Native([string]$Exe, [string[]]$Arguments) {
    $out = & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$Exe $($Arguments -join ' ') failed with exit code $LASTEXITCODE" }
    return $out
}

function Format-List([string[]]$Items) {
    return (($Items | ForEach-Object { "- ``$_``" }) -join "`n")
}

$repo = (Invoke-Native gh @('repo', 'view', '--json', 'nameWithOwner', '-q', '.nameWithOwner')).Trim()
if ($repo -eq $TemplateRepo) { Write-Host "Skipping: $repo is the template itself."; exit 0 }

$startBranch = (Invoke-Native git @('rev-parse', '--abbrev-ref', 'HEAD')).Trim()
$tmp = Join-Path ([IO.Path]::GetTempPath()) ("template-src-" + [guid]::NewGuid().ToString('N'))
try {
    Invoke-Native git @('clone', '--quiet', '--depth', '1', '--branch', $Ref, "https://github.com/$TemplateRepo.git", $tmp) | Out-Null
    $sha = (Invoke-Native git @('-C', $tmp, 'rev-parse', '--short', 'HEAD')).Trim()
    $syncArgs = @('-NoProfile', '-File', (Join-Path $tmp 'scripts/template-sync.ps1'), '-TemplateDir', $tmp)
    if ($SkipWorkflows) { $syncArgs += '-SkipWorkflows' }

    Invoke-Native git @('fetch', '--quiet', 'origin', $Base) | Out-Null
    & git fetch --quiet origin $Branch 2>$null
    $global:LASTEXITCODE = 0
    Invoke-Native git @('checkout', '--quiet', '-B', $Branch, "origin/$Base") | Out-Null
    $report = (Invoke-Native pwsh $syncArgs) -join "`n" | ConvertFrom-Json
    if ($report.changed.Count -eq 0) {
        Write-Host "No differences with $TemplateRepo@$sha. Nothing to open."
        exit 0
    }
    Write-Host "Differences with $TemplateRepo@${sha}:"
    $report.changed | ForEach-Object { Write-Host "  $_" }
    if ($DryRun) { exit 0 }

    Invoke-Native pwsh ($syncArgs + '-Apply') | Out-Null
    Invoke-Native git @('add', '--', '.') | Out-Null
    Invoke-Native git @('commit', '--quiet', '-m', "chore(template): sync with roblox-game-template@$sha") | Out-Null
    Invoke-Native git @('push', '--quiet', '--force-with-lease', '-u', 'origin', $Branch) | Out-Null

    $list = Format-List $report.changed
    $extra = ''
    if ($report.skippedWorkflows.Count -gt 0) {
        $extra += "`n`n**Not applied (needs a token with the ``workflow`` scope, ADR 0069):**`n" + (Format-List $report.skippedWorkflows)
    }
    if ($report.notInTemplate.Count -gt 0) {
        $extra += "`n`n**Matched by the manifest but absent from the template (kept, review by hand):**`n" + (Format-List $report.notInTemplate)
    }

    $open = (Invoke-Native gh @('pr', 'list', '--head', $Branch, '--state', 'open', '--json', 'number', '-q', '.[0].number')) -join ''
    if ($open.Trim()) {
        Invoke-Native gh @('pr', 'comment', $open.Trim(), '--body', "Branch refreshed from ``$TemplateRepo@$sha``.`n`n$list$extra") | Out-Null
        Write-Host "Refreshed PR #$($open.Trim())"
        exit 0
    }

    & gh label create template-sync --color 0E8A16 --description 'Files synced from the game template' 2>$null | Out-Null
    $global:LASTEXITCODE = 0
    $issueBody = "The template moved to ``$sha``. Files it owns (see ``.templatesync``) differ here:`n`n$list$extra`n`nThe sync PR closes this issue. Exclude game-specific paths in ``.templatesync.local``."
    $issueUrl = (Invoke-Native gh @('issue', 'create', '--title', "chore(template): sync with the game template@$sha", '--label', 'template-sync', '--body', $issueBody)).Trim()
    $number = ($issueUrl -split '/')[-1]
    $prBody = "Closes #$number`n`n## What changed`nFiles owned by the template (``.templatesync``) updated to ``$TemplateRepo@$sha``:`n`n$list$extra`n`n## How it was verified`nGenerated by ``scripts/template-sync-pr.ps1``: only manifest paths are touched and exclusions in ``.templatesync.local`` are honored. Review the diff; CI runs on the PR. It is never merged automatically."
    $pr = Invoke-Native gh @('pr', 'create', '--base', $Base, '--head', $Branch, '--title', "chore(template): sync with roblox-game-template@$sha", '--label', 'template-sync', '--body', $prBody)
    Write-Host "Opened $pr (issue #$number)"
}
finally {
    if ($startBranch -ne 'HEAD') { git checkout --quiet $startBranch 2>$null }
    if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue }
}
